# レインボーブリッジ（東京港連絡橋、芝浦〜台場の 3 径間 2 ヒンジ補剛トラス吊橋）for TOKYO OPEN DRIVE.
#
#   nix develop .#blender -c blender --background --factory-startup \
#     --python scripts/blender/landmarks.py -- public/models/rainbow_bridge.glb [preview-dir]
#
# A module of scripts/blender/landmarks.py (LANDMARK_MODULES; Builder / Palette / export / landmarks.json entry
# and previews stay there). The model is the structure only: two towers, main cables and hangers, the
# double-deck stiffening truss (chords, verticals, diagonals, floor beams, lateral bracing) and the two
# anchorages, plus their night lighting. It has no road surface, no deck slab and no collider: the
# roads on both decks (the expressway above; the 臨港道路, the ゆりかもめ guideway and the
# promenades below) are generated by the road side, which reads the deck levels this script writes to
# landmarks.json (`deckLevels`). The tops of both floors are left open for those slabs.
#
# Coordinates: +Y up in metres with y = T.P. height (baseHeight 0: the model's origin is on the
# 東京湾平均海面 at the middle of the main span), +Z = heading 111.226° (from the Shibaura tower to the
# Odaiba tower), +X = its left (the north-east side). Shibaura tower at z = −285, Odaiba tower at +285.
#
# Sources (details, trust and pitfalls in knowledge/rainbow-bridge-blender.md):
#   - 中央径間 570 m, 全長 798 m (cable 114 + 570 + 114), 主塔 T.P.+126 m, 桁下 T.P.+51.266 m,
#     支間割 111.5 + 570 + 111.5 m, 幅員 29.0 m: Wikipedia ja「レインボーブリッジ」(橋梁年鑑・『橋梁』1991),
#     首都高の開通 30 周年の主塔ツアー記事 (Impress Travel Watch 2023), 中部日本放送の点検記事.
#   - Plan (tower legs, cross beams, anchorage tiers, the bridge axis and the lanes): OpenStreetMap
#     relation 18497742 and the ways on it (© OpenStreetMap contributors, ODbL 1.0), 2026-11-10.
#   - Heights not published (girder at the towers, truss depth, top beam, struts, pier top): measured on
#     Wikimedia Commons "Rainbow Bridge, Tokyo, South view from Odaiba 20190419 1.jpg" (DXR,
#     CC BY-SA 4.0) scaled by the 126 m tower; the lower strut confirmed on "Rainbow Bridge (Tokyo) at
#     night 8.jpg" (Kakidai, CC BY-SA 4.0). Photos were only measured; no pixel is in the model.
#   - Lighting: 岩崎電気 case study (2020 LED renewal): towers cool white in the summer pattern (April
#     to October) and warm white in the winter pattern (November to March); the girder underside and
