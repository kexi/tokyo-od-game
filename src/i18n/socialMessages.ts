/** A Y screen string in `locale` (the UI's language by default), `{slots}` filled. */
export function st(key: SocialMessageKey, params?: Params, locale: Locale = getLocale()): string {
  const text = TABLES[locale][key] || SOCIAL_JA[key];
  return interpolate(text, params);
}

/** A label that follows a count: English has a singular for one. */
export function stCount(
  key: SocialMessageKey,
  n: number,
  params?: Params,
  locale: Locale = getLocale(),
): string {
  const isOne = locale === "en" && n === 1;
  const one = isOne ? EN_ONE[key] : undefined;
  return one ? interpolate(one, params) : st(key, params, locale);
}

